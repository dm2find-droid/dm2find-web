/** countryName(locale, 'FR', 'France') -> 'Frankrijk' */
export function countryName(locale: Locale, code: string, fallback: string): string {
  return COUNTRY[code]?.[locale] ?? fallback;
}

const DICT: Record<Locale, Dict> = { en, fr, de, nl, es };

/** t('fr')('dest.title', { place: 'Lille' }) */
export function t(locale: Locale) {
  const table = DICT[locale] ?? DICT[DEFAULT_LOCALE];
  return (key: string, vars?: Record<string, string | number>) => {
    const raw = table[key] ?? DICT[DEFAULT_LOCALE][key] ?? key;
    return vars
      ? raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
      : raw;
  };
}

/** '/destinations/lille' -> '/fr/destinations/lille' (en blijft zonder prefix) */
export function localeHref(locale: Locale, path: string): string {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return locale === DEFAULT_LOCALE ? clean : `/${locale}${clean}`;
}

/** Bestaat deze route in alle talen? Zo niet: geen hreflang, geen prefix. */
export function isLocalised(path: string): boolean {
  return LOCALISED_ROUTES.some(r => path.startsWith(r));
}

/** Leest de taal uit het pad; onbekend of afwezig betekent Engels. */
export function localeFromPath(pathname: string): Locale {
  const seg = pathname.split('/')[1] as Locale;
  return (LOCALES as readonly string[]).includes(seg) ? seg : DEFAULT_LOCALE;
}

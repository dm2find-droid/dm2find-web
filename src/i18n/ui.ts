/**
 * Vertalingen van de vaste teksten. Data (namen van bestemmingen, licentie-
 * teksten, bronnamen) blijft staan zoals de bron hem levert — die vertalen we
 * niet, want dan claim je een naam die de DMO zelf niet gebruikt.
 *
 * Een ontbrekende sleutel valt terug op het Engels in plaats van leeg te
 * renderen: een half vertaalde pagina is vervelend, een lege regel is stuk.
 */
export const LOCALES = ['en', 'fr', 'de', 'nl', 'es', 'it', 'zh', 'ja', 'ko'] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'en';

/**
 * De URL-prefix en de taalcode zijn niet hetzelfde ding. `/zh/` leest prettig
 * in een adresbalk, maar `lang="zh"` en `hreflang="zh"` zeggen alleen "Chinees"
 * zonder te zeggen wélk schrift — en dat is precies de vraag bij Chinees.
 * `zh-Hans` zegt: vereenvoudigd. Voor de andere talen is de prefix toevallig
 * al een geldige tag, dus die staan hier niet in.
 */
const BCP47: Partial<Record<Locale, string>> = { zh: 'zh-Hans' };

/** De taalcode voor lang= en hreflang=. */
export function langTag(locale: Locale): string {
  return BCP47[locale] ?? locale;
}

/** og:locale wil language_TERRITORY, niet een kale taalcode. */
const OG_LOCALE: Record<Locale, string> = {
  en: 'en_GB', fr: 'fr_FR', de: 'de_DE', nl: 'nl_NL', es: 'es_ES',
  it: 'it_IT', zh: 'zh_CN', ja: 'ja_JP', ko: 'ko_KR',
};
export function ogLocale(locale: Locale): string {
  return OG_LOCALE[locale] ?? OG_LOCALE[DEFAULT_LOCALE];
}

